"""Load Claude's one-time hand labels (analysis/claude_thoughts.json) into the claude_thoughts table.

    python analysis/load_claude_thoughts.py [--seen-file backups/mood_labels_....csv]

The labels were written once, by hand, and cannot be regenerated by a script: this only loads the snapshot. The
optional --seen-file is the backup of the user's first (since cleared) labels that Claude had already seen; those
songs are flagged saw_label_before so they can be scored separately.
"""
import argparse
import csv
import json
import os
import sys

import psycopg2
from dotenv import load_dotenv

HERE = os.path.dirname(os.path.abspath(__file__))
MOODS = {"calm", "mellow", "intense", "upbeat"}
LEVELS = {"low", "medium", "high"}


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--seen-file", help="CSV with a track_id column: songs whose earlier label Claude had seen")
    args = parser.parse_args()

    load_dotenv(os.path.join(HERE, "..", ".env"))
    data = json.load(open(os.path.join(HERE, "claude_thoughts.json"), encoding="utf-8"))
    labels = data["labels"]
    for tid, (mood, conf, reason) in labels.items():
        assert mood in MOODS and conf in LEVELS and reason, (tid, mood, conf)

    seen = set()
    if args.seen_file:
        with open(args.seen_file, newline="", encoding="utf-8") as f:
            seen = {row["track_id"] for row in csv.DictReader(f)}  # only the ids are read, never the moods

    conn = psycopg2.connect(host=os.getenv("DB_HOST"), port=os.getenv("DB_PORT"), dbname=os.getenv("DB_NAME"),
                            user=os.getenv("DB_USER"), password=os.getenv("DB_PASSWORD"))
    with conn, conn.cursor() as cur:
        cur.execute("""
            CREATE TABLE IF NOT EXISTS claude_thoughts (
                track_id          TEXT PRIMARY KEY,
                mood              TEXT NOT NULL,
                confidence        TEXT NOT NULL,
                reason            TEXT NOT NULL,
                saw_label_before  BOOLEAN NOT NULL DEFAULT false,
                labelled_at       TIMESTAMPTZ DEFAULT now()
            )""")
        cur.execute("SELECT track_id FROM mood_labels")  # ids only, to check these are the songs that were labelled
        labelled_ids = {r[0] for r in cur.fetchall()}
        unknown = set(labels) - labelled_ids
        missing = labelled_ids - set(labels)
        if unknown or missing:
            print(f"WARNING: {len(unknown)} ids in the snapshot are not in mood_labels; {len(missing)} labelled songs are missing from it")
        for tid, (mood, conf, reason) in labels.items():
            cur.execute("""
                INSERT INTO claude_thoughts (track_id, mood, confidence, reason, saw_label_before)
                VALUES (%s, %s, %s, %s, %s)
                ON CONFLICT (track_id) DO UPDATE SET mood = EXCLUDED.mood, confidence = EXCLUDED.confidence,
                    reason = EXCLUDED.reason, saw_label_before = EXCLUDED.saw_label_before""",
                        (tid, mood, conf, reason, tid in seen))
    conn.close()
    flagged = len(seen & set(labels))
    print(f"loaded {len(labels)} labels; {flagged} flagged as songs whose earlier label I had seen")


if __name__ == "__main__":
    sys.exit(main())
